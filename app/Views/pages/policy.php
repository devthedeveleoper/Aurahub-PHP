  <h2>What is Allowed</h2>
  <p>Almost everything. This includes, but is not limited to:</p>
  <ul style="margin-left: 1.5rem; margin-bottom: 1.5rem;">
    <li>Political speech and opinions of any kind</li>
    <li>Satire, parody, and edgy humor</li>
    <li>Criticism of public figures, organizations, or governments</li>
    <li>Controversial or unpopular viewpoints</li>
    <li>Anything that is legal, even if people find it offensive</li>
  </ul>

  <h2>What is NOT Allowed (Will be removed)</h2>
  <p>We strictly remove content that violates the law. If your video is removed, you will be notified with the specific legal reason. Our reporting system is restricted to the following categories:</p>
  <ul style="margin-left: 1.5rem; margin-bottom: 1.5rem;">
    <li><strong>Child Exploitation Material (CSAM):</strong> Instantly removed and reported to authorities.</li>
    <li><strong>Terrorism Recruitment / Propaganda:</strong> Content intended to recruit for or promote acts of terrorism.</li>
    <li><strong>Doxxing:</strong> Publishing someone's private, non-public information (e.g., home address, private phone number) with malicious intent.</li>
    <li><strong>Threats of Violence:</strong> Direct, credible threats of real-world physical violence against specific individuals or groups.</li>
    <li><strong>Other Illegal Content:</strong> Content that is explicitly illegal in our hosting jurisdiction.</li>
  </ul>

  <h2>Moderation Transparency</h2>
  <p>When a video is removed, the uploader will receive a notification detailing exactly why the action was taken. We do not use automated content removal systems (except for known CSAM hashes). Human moderators review all reports to ensure enforcement strictly aligns with this legal-only policy.</p>

